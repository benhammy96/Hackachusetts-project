/**
 * Renders an AI-generated explanation of a site's suitability score.
 * Placeholder UI for the AI feature.
 */

import type { ExplanationResponse } from "@/types/models";

interface ExplanationCardProps {
  explanation?: ExplanationResponse;
}

export function ExplanationCard({ explanation }: ExplanationCardProps) {
  if (!explanation) {
    return (
      <div className="rounded-lg border border-slate-200 p-4 text-sm text-slate-500">
        An AI explanation will appear here once a site is scored.
      </div>
    );
  }

  return (
    <div className="rounded-lg border border-slate-200 bg-slate-50 p-4">
      <h2 className="mb-2 text-lg font-semibold text-atlas-ink">Why this score?</h2>
      <p className="mb-2 text-sm font-medium text-slate-800">{explanation.summary}</p>
      <p className="text-sm text-slate-600">{explanation.details}</p>
      <p className="mt-3 text-xs text-slate-400">Generated by {explanation.model}</p>
    </div>
  );
}
